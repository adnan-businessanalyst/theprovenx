import { mkdirSync, readdirSync, statSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const MOCKUPS_DIR = "src/components/mockups";
const GENERATED_MODULE = "src/.generated/mockup-components.ts";

function walk(dir, acc = []) {
  let entries = [];
  try {
    entries = readdirSync(dir);
  } catch {
    return acc;
  }
  for (const name of entries) {
    if (name.startsWith("_")) continue;
    const abs = path.join(dir, name);
    const st = statSync(abs);
    if (st.isDirectory()) {
      if (name.startsWith("_")) continue;
      walk(abs, acc);
    } else if (name.endsWith(".tsx") && !name.startsWith("_")) {
      acc.push(abs);
    }
  }
  return acc;
}

const mockupsAbs = path.join(root, MOCKUPS_DIR);
const files = walk(mockupsAbs).map((abs) =>
  path.relative(root, abs).split(path.sep).join("/"),
);

const entries = files
  .map((f) => {
    const globKey = "./" + f.slice("src/".length);
    const importPath = path.posix.relative("src/.generated", f);
    return `  ${JSON.stringify(globKey)}: () => import(${JSON.stringify(importPath)})`;
  })
  .join(",\n");

const source = [
  "// This file is auto-generated by scripts/generate-mockup-modules.mjs.",
  "type ModuleMap = Record<string, () => Promise<Record<string, unknown>>>;",
  "export const modules: ModuleMap = {",
  entries,
  "};",
  "",
].join("\n");

const out = path.join(root, GENERATED_MODULE);
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, source);
console.log(`Generated ${GENERATED_MODULE} (${files.length} mockups)`);
